/* notes 里可以补几行：{k: 行名, after: 插在哪一行后面, dd: 显示的值, t: 解释的标题, p: 解释的段落}。
   行名和生成的某一行相同时，顶替那一行。 */
function addRows(rows,extra){
  (extra||[]).forEach(r=>{
    const same=rows.findIndex(x=>x.k===r.k);
    if(same>=0){                       // 和生成的行同名：手写的顶替它；手写的没有「典籍」一段时，把生成的那一段留下
      const keep=(rows[same].p||[]).filter(x=>x&&x[0]==='典籍'&&!(r.p||[]).some(y=>y&&y[0]==='典籍'));
      rows[same]=Object.assign({},r,{p:(r.p||[]).slice(0,1).concat(keep,(r.p||[]).slice(1))});
      return;
    }
    const i=rows.findIndex(x=>x.k===r.after);rows.splice(i<0?rows.length:i+1,0,r);
  });
  return rows;
}

